/* =========================================
   OPEN EQUALITY POPUP
========================================= */

function showEqualityInfo(type) {

    const data = equalityInformation[type];

    if (!data) {
        return;
    }

    const modal =
        document.getElementById("equalityInfoModal");

    if (!modal) {
        return;
    }

    document.getElementById("equalityInfoIcon").textContent =
        data.icon;

    document.getElementById("equalityInfoTitle").textContent =
        data.title;

    document.getElementById("equalityInfoContent").innerHTML =
        data.content;

    modal.classList.add("show");

    document.body.style.overflow = "hidden";
}


/* =========================================
   CLOSE EQUALITY POPUP
========================================= */

function closeEqualityInfo() {

    const modal =
        document.getElementById("equalityInfoModal");

    if (!modal) {
        return;
    }

    modal.classList.remove("show");

    document.body.style.overflow = "";

    stopEqualityInfoSpeech();
}


/* =========================================
   EQUALITY POPUP TEXT TO SPEECH
========================================= */

function speakEqualityInfo() {

    if (!("speechSynthesis" in window)) {

        alert(
            "🔊 Audio is not supported by this browser."
        );

        return;
    }

    const title =
        document.getElementById("equalityInfoTitle").innerText;

    const content =
        document.getElementById("equalityInfoContent").innerText;

    window.speechSynthesis.cancel();

    const speech =
        new SpeechSynthesisUtterance(
            title + ". " + content
        );

    const savedLanguage =
        localStorage.getItem("nariLanguage");

    if (savedLanguage === "mr") {

        speech.lang = "mr-IN";

    }

    else if (savedLanguage === "hi") {

        speech.lang = "hi-IN";

    }

    else {

        speech.lang = "en-IN";

    }

    speech.rate = 0.9;

    window.speechSynthesis.speak(speech);
}


/* =========================================
   STOP POPUP AUDIO
========================================= */

function stopEqualityInfoSpeech() {

    if ("speechSynthesis" in window) {

        window.speechSynthesis.cancel();

    }

}


/* =========================================
   CLOSE POPUP WHEN CLICKING OUTSIDE
========================================= */

window.addEventListener(
    "click",
    function(event) {

        const modal =
            document.getElementById(
                "equalityInfoModal"
            );

        if (
            modal &&
            event.target === modal
        ) {

            closeEqualityInfo();

        }

    }
);


/* =========================================
   CLOSE POPUP WITH ESC KEY
========================================= */

document.addEventListener(
    "keydown",
    function(event) {

        if (event.key === "Escape") {

            closeEqualityInfo();

        }

    }
);




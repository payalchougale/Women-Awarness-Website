let score = 0;


function answerQuestion(correct) {

    const result =
        document.getElementById(
            "checkResult"
        );


    if (!result) {
        return;
    }


    if (correct) {

        score++;

        result.innerHTML =
            "✅ Correct! Equality means everyone " +
            "deserves dignity, opportunity and " +
            "fair treatment.";

    }


    else {

        result.innerHTML =
            "❌ Try again.";

    }


    if (score >= 3) {

        result.innerHTML =
            "🌸 Excellent! You understand the " +
            "basic principles of equality.";

    }

}



/* =========================================
   TEXT TO SPEECH
========================================= */

function speakEquality() {

    if (
        !("speechSynthesis" in window)
    ) {

        alert(
            "🔊 Audio is not supported by this browser."
        );

        return;
    }


    stopEqualitySpeech();


    const text =
        document.body.innerText;


    const speech =
        new SpeechSynthesisUtterance(
            text
        );


    const language =
        document.getElementById(
            "languageSelect"
        );


    if (
        language &&
        language.value === "mr"
    ) {

        speech.lang =
            "mr-IN";

    }

    else if (
        language &&
        language.value === "hi"
    ) {

        speech.lang =
            "hi-IN";

    }

    else {

        speech.lang =
            "en-IN";

    }


    speech.rate = 0.85;

    speech.pitch = 1;


    window.speechSynthesis.speak(
        speech
    );

}



/* =========================================
   STOP AUDIO
========================================= */

function stopEqualitySpeech() {

    if (
        "speechSynthesis"
        in window
    ) {

        window.speechSynthesis.cancel();

    }

}



/* =========================================
   FAQ
========================================= */

function toggleEqualityFAQ(button) {

    const answer =
        button.nextElementSibling;


    if (!answer) {
        return;
    }


    const isOpen =
        answer.classList.contains(
            "show"
        );


    /* Close all answers */

    document
        .querySelectorAll(
            ".faq-answer"
        )
        .forEach(
            function(item) {

                item.classList.remove(
                    "show"
                );

            }
        );


    /* Reset icons */

    document
        .querySelectorAll(
            ".faq-question span"
        )
        .forEach(
            function(icon) {

                icon.innerText = "+";

            }
        );


    /* Open selected answer */

    if (!isOpen) {

        answer.classList.add(
            "show"
        );


        const icon =
            button.querySelector(
                "span"
            );


        if (icon) {

            icon.innerText = "−";

        }

    }

}



/* =========================================
   LANGUAGE
========================================= */

document.addEventListener(
    "DOMContentLoaded",
    function() {

        const languageSelect =
            document.getElementById(
                "languageSelect"
            );


        const savedLanguage =
            localStorage.getItem(
                "nariLanguage"
            );


        if (
            languageSelect &&
            savedLanguage
        ) {

            languageSelect.value =
                savedLanguage;

        }


        if (languageSelect) {

            languageSelect.addEventListener(
                "change",
                function() {

                    localStorage.setItem(
                        "nariLanguage",
                        this.value
                    );

                }
            );

        }

    }
);